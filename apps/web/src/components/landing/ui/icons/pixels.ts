export function pixelPath(name: string): string | undefined {
  if (!(name in SHAPES)) return undefined;
  const rows = Object.entries(SHAPES).find(([key]) => key === name)?.[1] ?? [];

  return rows
    .flatMap((row, y) =>
      Array.from(row, (cell, x) =>
        cell === "#" && 1 > bayerThreshold(x, y) ? `M${x} ${y + 3}h1v1h-1z` : "",
      ),
    )
    .join("");
}
